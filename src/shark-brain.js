const PREFIX = 'והבלמשכ';
const norm = (t) =>
  ` ${t
    .replace(/[֑-ׇ]/g, '')
    .replace(/["'״׳]/g, '')
    .replace(/[^א-תa-zA-Z0-9₪ ]+/g, ' ')
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .trim()} `;
const words = (n) => n.trim().split(' ').filter(Boolean);

// A key with a space is a phrase. "stem*" matches the start of a word. A plain word matches the
// word itself, also with up to two Hebrew prefix letters (ו, ה, ב, ל, מ, ש, כ).
function hits(n, ws, key) {
  const k = norm(key).trim();
  if (k.includes(' ')) return new RegExp(` [${PREFIX}]{0,2}${k}`).test(n) ? k.length : 0;
  const stem = key.endsWith('*');
  const base = stem ? norm(key.slice(0, -1)).trim() : k;
  for (const w of ws) {
    for (let p = 0; p <= 2 && p < w.length; p++) {
      if (p && !PREFIX.includes(w[p - 1])) break;
      const rest = w.slice(p);
      if (stem ? rest.startsWith(base) : rest === base) return base.length + 1;
    }
  }
  return 0;
}
const score = (n, ws, t) => t.keys.reduce((s, k) => s + hits(n, ws, k), 0) * (t.w || 1);

