// The support answers in data.js: which open question each one leaves.
const SUPPORT_OPEN = ['noaPrep', 'lonely', 'tried'];

// ctx: { offer, open, n } from the shark's last message. Returns { text, offer?, open? }.
export function sharkReply(text, ctx = {}) {
  const n = norm(text);
  const ws = words(n);

  // 1. Real distress: a human, every time.
  if (SHARK_DISTRESS.keys.some((k) => n.includes(norm(k).trim()))) return { text: SHARK_DISTRESS.a };

  // 2. One of the suggested questions, word for word.
  const asked = SHARK_ASKS.find((x) => x.q === text.trim());
  if (asked) return { text: (GENDER === 'f' && asked.aF) || asked.a, offer: asked.from === 'טבלת הלידים' ? 'noa' : undefined };

  // 3. The user is answering the practice question: feedback on the answer.
  if (ctx.open === 'practice') return { text: OPENS.practice() };

  // 4. Score every topic, the support answers included.
  const support = SHARK_SUPPORT.map((x, i) => ({ id: `support${i}`, w: 0.6, keys: [x.q, ...x.keys], a: () => x.a, ...(SUPPORT_OPEN[i] === 'noaPrep' ? { offer: 'noaPrep' } : { open: SUPPORT_OPEN[i] }) }));
  let best = null;
  let top = 0;
  for (const t of [...support, ...TOPICS]) {
    const s = score(n, ws, t);
    if (s > top) (top = s), (best = t);
  }

  // 5. A short yes or no to what the shark just offered.
  const short = ws.length <= 4;
  const weak = !best || ['thanks', 'greet'].includes(best.id);
  if (short && ctx.offer && OFFERS[ctx.offer] && (weak || best.id === 'thanks')) {
    if (YES.some((y) => hits(n, ws, y))) {
      const o = OFFERS[ctx.offer];
      return { text: o.a(), offer: o.offer, open: o.open };
    }
    if (NO.some((y) => hits(n, ws, y))) return { text: 'בסדר גמור. אני כאן כשתרצה. יש משהו אחר שמעסיק אותך?'.replace('כשתרצה', you('כשתרצה', 'כשתרצי')) };
  }

  // A reply to "tell me more" that also names a topic: thank for it, then answer the topic.
  // A business question said with a feeling ("I tried posting and nobody called"): the feeling first.
  const told = ['tried', 'lonely', 'heavy'].includes(ctx.open) && best && !best.id.startsWith('support') && !['thanks', 'greet'].includes(best.id);
  // The same feeling again, right after the shark answered it: go on from there, don't repeat.
  const feeling = best && (best.id.startsWith('support') || best.id === 'tired');
  if (feeling && best.id === ctx.topic) {
    const key = best.open && OPENS[best.open] ? best.open : 'general';
    return { text: OPENS[key](ctx.n || 0), open: 'general', topic: best.id };
  }
  const tired = TOPICS.find((x) => x.id === 'tired');
  const feel = best && !best.id.startsWith('support') && !['tired', 'offtopic'].includes(best.id) ? [...support, tired].find((x) => score(n, ws, x) > 0) : null;
  const FEEL = {
    support0: 'קודם כל, זה בסדר להרגיש ככה, גם הטובים ביותר מרגישים. ',
    support1: `${you('אתה', 'את')} לא לבד בזה, אני כאן. `,
    tired: 'שומע שזה מלחיץ, וזה נורמלי לגמרי. זה אומר שאכפת לך. ',
    support2: 'זה מתסכל כשמשקיעים ולא רואים תוצאה, וזה קורה כמעט לכולם בהתחלה. זה מידע, לא כישלון. ',
  };
  const lead = told ? 'תודה שסיפרת, זה עוזר לי להבין. ' : feel ? FEEL[feel.id] : '';
  const closed = ['noa', 'yael'].includes(best?.id) && WON.test(n);
  if (best) return { text: lead + best.a(n), offer: closed ? undefined : best.offer, open: best.open, topic: best.id };

  // 6. A reply to the shark's own question.
  if (ctx.open && OPENS[ctx.open]) return { text: OPENS[ctx.open](ctx.n || 0), open: 'general' };

  // 7. Nothing fits: answer this message, not a canned line.
  const snip = words(text.replace(/[?!.,]/g, ' ')).slice(0, 7).join(' ');
  const q = /[?]/.test(text) || /^(איך|מה|למה|מתי|כמה|האם|איפה|מי|אפשר|כדאי)\s/.test(text.trim());
  const variants = q
    ? [
        `שאלה טובה. כדי לענות על "${snip}" לפי ${USER.business} ולא בכללי, ${you('ספר', 'ספרי')} לי עוד משפט: זה קשור למטופלים, לכסף, לשיווק או למשהו אחר?`,
        `לגבי "${snip}": ${you('תן', 'תני')} לי עוד קצת הקשר. מה קרה שגרם לך לשאול את זה? ככה התשובה תהיה על העסק שלך.`,
      ]
    : [
        `הבנתי, "${snip}". ${you('ספר', 'ספרי')} לי עוד קצת, ומה היית רוצה שיקרה? ככה אוכל לעזור בדיוק.`,
        `קיבלתי. מה שכתבת חשוב לי. מה הצעד שהכי מעסיק אותך בזה עכשיו? נתחיל ממנו.`,
      ];
  return { text: variants[(ctx.n || 0) % variants.length], open: 'general' };
}
